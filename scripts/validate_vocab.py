#!/usr/bin/env python3
"""Validate vocab/*.json (or a merged vocab.json) against SCHEMA.md rules.

Checks:
  - id: present, unique, ascii-slug shaped
  - ja, en: present and non-empty
  - domain: in enum
  - (ja, en) pair: unique (no duplicate concept entries)
  - null de/zh: must carry a non-empty `notes` explaining why
  - per-language duplicate-token AUDIT for ja/en/de/zh (structural
    collision: two different concept ids sharing the same token in a
    language column makes any downstream embedding distance between them
    exactly 0 by construction, not by measurement). A collision is NOT
    itself a violation (many are real lexical facts -- see
    vocab/SCHEMA.md `token_collision`); the violation is an *unannotated*
    collision (see check_token_collision_annotations below). The audit
    numbers are always reported as three together, never a single scalar:
    species (distinct duplicated tokens), affected (entries touched),
    surplus = affected - species. null values are excluded from grouping
    and reported separately so the metric can't be moved by null rate.
  - token_collision annotation consistency: every entry in `vocab.json`
    whose ja/en/de/zh token collides with another entry's must carry a
    matching `token_collision` field (generated by
    build_vocab.build_merged -> compute_token_collisions). Missing or
    stale annotation -> violation. Presence of a collision is not a
    violation; an *unannotated* one is.
  - token notation discipline: ja/en/de/zh tokens must be one lexical item.
    Parenthetical disambiguation, gender-form markers, and slash-joined
    alternatives belong in `notes`, not the token -> any token containing
    '(' ')' or '/' is a violation.
  - de == en (both non-null): flags likely-untranslated/borrowed terms for
    review
  - zh Traditional-character contamination: every non-null `zh` token is
    passed through ICU's Traditional-Simplified transform (via a Swift
    subprocess, macOS NLEmbedding-adjacent tooling); if the transform
    changes the string, the field still holds Traditional forms. zh == ja
    is explicitly NOT checked here -- same-form Simplified/Kanji overlap is
    not a defect (audited separately, DEFECT 0).
  - vocab.json staleness: rebuilds the merge from vocab/*.json (via
    build_vocab.build_merged, which also recomputes token_collision) and
    compares structurally against the committed vocab.json; any mismatch
    is a violation. This transitively catches embed_en going stale too
    (embed_check.py writes into vocab/*.json; if vocab.json wasn't
    rebuilt after, this fires).

Exits non-zero on any violation.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_vocab  # noqa: E402  (sibling module, path patched above)

ROOT = Path(__file__).resolve().parent.parent
DOMAIN_ENUM = {"cosmology", "emotion", "craft", "relations", "seven", "daily"}
ID_RE = re.compile(r"^[a-z0-9_]+$")
LANGS = ("ja", "en", "de", "zh")

# de == en is flagged by default as a likely-untranslated/borrowed term. This
# is an explicit per-id allowlist for cases where identical de/en IS the
# correct attested German word -- international/proper-noun vocabulary
# (Roman/Greek deity-derived planet and constellation names use the same
# spelling in German and English). Individual id enumeration ONLY, no
# pattern match: a pattern would silently swallow future genuine
# untranslated-term defects instead of forcing a one-line human decision
# per id (per operator instruction, judgment 3, 2026-08-06).
DE_EN_IDENTICAL_ALLOWLIST = {
    "orion": "constellation/mythological-figure name; German uses the same "
              "Latin/Greek-derived proper noun 'Orion' as English",
    "venus_planet": "planet name; German uses the same Latin deity-derived "
                     "proper noun 'Venus' as English",
    "mars_planet": "planet name; German uses the same Latin deity-derived "
                    "proper noun 'Mars' as English",
    "jupiter_planet": "planet name; German uses the same Latin deity-derived "
                       "proper noun 'Jupiter' as English",
    "saturn_planet": "planet name; German uses the same Latin deity-derived "
                      "proper noun 'Saturn' as English",
    "uranus_planet": "planet name; German uses the same Greek deity-derived "
                      "proper noun 'Uranus' as English",
    "pluto_planet": "planet name; German uses the same Latin deity-derived "
                     "proper noun 'Pluto' as English (dwarf-planet "
                     "reclassification in 2006 does not change the lexeme)",
}


def load_entries(paths):
    entries = []
    for path in paths:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            print(f"ERROR {path}: invalid JSON: {e}", file=sys.stderr)
            sys.exit(1)
        if not isinstance(data, list):
            print(f"ERROR {path}: expected a JSON array", file=sys.stderr)
            sys.exit(1)
        for entry in data:
            entries.append((path, entry))
    return entries


def is_blank(value):
    return value is None or (isinstance(value, str) and not value.strip())


def check_basic(entries):
    """id/ja/en/domain/pair/null-notes checks. Returns (errors, per_domain)."""
    errors = []
    seen_ids = {}
    seen_pairs = {}
    per_domain = {}

    for path, e in entries:
        eid = e.get("id")
        ja = e.get("ja")
        en = e.get("en")
        domain = e.get("domain")

        if not eid:
            errors.append(f"{path}: missing id in {e}")
        elif not ID_RE.match(eid):
            errors.append(f"{path}: id '{eid}' is not a valid ascii slug")
        elif eid in seen_ids:
            errors.append(f"{path}: duplicate id '{eid}' (first in {seen_ids[eid]})")
        else:
            seen_ids[eid] = path

        if not ja or not str(ja).strip():
            errors.append(f"{path}: entry '{eid}' has empty ja")
        if not en or not str(en).strip():
            errors.append(f"{path}: entry '{eid}' has empty en")

        if domain not in DOMAIN_ENUM:
            errors.append(f"{path}: entry '{eid}' has invalid domain '{domain}'")
        else:
            per_domain[domain] = per_domain.get(domain, 0) + 1

        if ja and en:
            pair = (ja, en)
            if pair in seen_pairs:
                errors.append(
                    f"{path}: duplicate (ja,en) pair {pair} "
                    f"(first id={seen_pairs[pair]}, this id={eid})"
                )
            else:
                seen_pairs[pair] = eid

        for field in ("de", "zh"):
            if e.get(field) is None and not str(e.get("notes") or "").strip():
                errors.append(
                    f"{path}: entry '{eid}' has null {field} but empty notes "
                    f"(must state why no translation exists)"
                )

    return errors, per_domain


def duplicate_token_audit(entries, langs=LANGS):
    """Per-language duplicate-token audit -- informational, not a violation.

    Returns summary only. summary[lang] = (null_count, species, affected,
    surplus). All three of species/affected/surplus are always reported
    together -- a single scalar duplicate count is exactly the failure
    mode that caused a prior audit to over-report (it subtracted a
    null-inflated denominator from a null-including numerator). null
    entries are excluded from grouping and counted separately so they
    cannot move species/affected/surplus at all.

    Whether an unannotated collision is a VIOLATION is decided by
    check_token_collision_annotations, not here -- a collision existing is
    a lexical fact, not a defect (see vocab/SCHEMA.md `token_collision`).
    """
    summary = {}
    for lang in langs:
        groups = {}
        null_count = 0
        for path, e in entries:
            v = e.get(lang)
            if is_blank(v):
                null_count += 1
                continue
            groups.setdefault(v, []).append(e.get("id"))
        dups = {tok: ids for tok, ids in groups.items() if len(ids) > 1}
        species = len(dups)
        affected = sum(len(ids) for ids in dups.values())
        surplus = affected - species
        summary[lang] = (null_count, species, affected, surplus)
    return summary


def check_token_collision_annotations(root):
    """vocab.json entries with a real token collision must carry a
    matching `token_collision` annotation (see build_vocab.py); entries
    with none must carry token_collision == None. Ground truth is
    recomputed independently from the raw ja/en/de/zh fields (ignoring
    whatever token_collision currently says) via the same function
    build_vocab.build_merged uses, so this check cannot share a failure
    mode with whatever produced the field.
    """
    vocab_json = root / "vocab.json"
    if not vocab_json.exists():
        return [f"{vocab_json} does not exist"]
    try:
        committed = json.loads(vocab_json.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        return [f"{vocab_json}: invalid JSON: {e}"]
    expected = build_vocab.compute_token_collisions(committed)
    violations = []
    for e in committed:
        eid = e.get("id")
        want = expected.get(eid)
        have = e.get("token_collision")
        if want != have:
            violations.append(
                f"id '{eid}': token_collision is {have!r}, expected {want!r} "
                f"(run scripts/build_vocab.py to regenerate)"
            )
    return violations


TOKEN_NOTATION_RE = re.compile(r"[()/]")


def check_token_notation(entries, langs=LANGS):
    """Token = one lexical item. Parenthetical disambiguation, gender-form
    markers ('Bekannte(r)'), and slash alternatives belong in `notes`.
    """
    violations = []
    for path, e in entries:
        eid = e.get("id")
        for lang in langs:
            v = e.get(lang)
            if v and TOKEN_NOTATION_RE.search(v):
                violations.append(
                    f"id '{eid}': {lang} token {v!r} contains '(' ')' or '/' "
                    f"-- move annotation/disambiguation/gender-marking to notes"
                )
    return violations


def check_de_eq_en(entries, allowlist=DE_EN_IDENTICAL_ALLOWLIST):
    """Flag de == en (both non-null) as a likely-untranslated/borrowed term,
    except for ids in DE_EN_IDENTICAL_ALLOWLIST (individual-id enumeration
    only -- see comment above the allowlist; no pattern match).
    """
    violations = []
    for path, e in entries:
        de, en, eid = e.get("de"), e.get("en"), e.get("id")
        if de and en and de == en and eid not in allowlist:
            violations.append(
                f"id '{eid}': de == en == {de!r} "
                f"(possible untranslated/borrowed term; verify and document)"
            )
    return violations


def check_zh_traditional(entries, root):
    """Detect Traditional-only forms in the `zh` field via ICU transform.

    zh == ja is deliberately NOT checked -- audited separately as DEFECT 0.
    """
    # The swift companion script is a fixed asset beside this file, not
    # part of the (possibly fixture) --root being validated.
    script = ROOT / "scripts" / "zh_traditional_check.swift"
    by_token_ids = {}
    for _, e in entries:
        zh = e.get("zh")
        if is_blank(zh):
            continue
        by_token_ids.setdefault(zh, []).append(e.get("id"))
    unique_zh = sorted(by_token_ids)
    if not unique_zh:
        return []
    payload = json.dumps(unique_zh, ensure_ascii=False)
    try:
        run = subprocess.run(
            ["swift", str(script)],
            input=payload,
            text=True,
            capture_output=True,
            check=False,
        )
    except FileNotFoundError:
        return [
            "zh Traditional-Simplified check could not run: 'swift' binary not "
            "found (requires macOS + Swift toolchain; do not silently skip -- "
            "fix the environment or explicitly waive this check)"
        ]
    if run.returncode != 0:
        return [
            f"zh Traditional-Simplified check subprocess failed "
            f"(exit {run.returncode}): {run.stderr.strip()}"
        ]
    lines = [ln for ln in run.stdout.splitlines() if ln]
    if len(lines) != len(unique_zh):
        return [
            f"zh Traditional-Simplified check: expected {len(unique_zh)} result "
            f"lines, got {len(lines)}"
        ]
    violations = []
    for line in lines:
        orig, simplified = line.split("\t", 1)
        if orig != simplified:
            ids = by_token_ids.get(orig, ["?"])
            violations.append(
                f"zh field {orig!r} (ids {sorted(ids)}) contains Traditional-only "
                f"forms; ICU Traditional-Simplified transform yields {simplified!r}"
            )
    return violations


EMBED_EN_TRUTHY_RE = re.compile(r"\bif\b.*\bembed_en\b")
EMBED_EN_SAFE_MARKERS = ("is none", "is true", "is false", "==", "!=")


def check_embed_en_truthiness(root):
    """Best-effort static scan: flag `if ...embed_en...` lines that don't
    use an explicit is-None/is-True/is-False/==/!= comparison. embed_en is
    3-valued (null=unmeasured, false=method limitation, true=found) --
    `if not e["embed_en"]` silently collapses null into false. This is a
    regex heuristic over source text, not real static analysis: it can
    miss multi-line conditions and cannot see through aliasing. Detect
    what's cheaply detectable; do not claim completeness.
    """
    violations = []
    for path in sorted(root.rglob("*.py")):
        rel_parts = path.relative_to(root).parts
        if ".scratch" in rel_parts or "tests" in rel_parts:
            continue
        if path.name == "validate_vocab.py":
            continue  # this file's own docstrings mention embed_en
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except (UnicodeDecodeError, OSError):
            continue
        for lineno, line in enumerate(lines, 1):
            if not EMBED_EN_TRUTHY_RE.search(line):
                continue
            lowered = line.lower()
            if any(marker in lowered for marker in EMBED_EN_SAFE_MARKERS):
                continue
            violations.append(
                f"{path}:{lineno}: truthy check on embed_en without an "
                f"explicit is-None/is-True/is-False/==/!= comparison -- "
                f"null (unmeasured) would silently read as false: {line.strip()!r}"
            )
    return violations


def check_stale(root):
    """vocab.json must equal a fresh merge of vocab/*.json (build_vocab.py)."""
    vocab_dir = root / "vocab"
    vocab_json = root / "vocab.json"
    if not vocab_dir.exists():
        return [f"{vocab_dir} does not exist"]
    if not vocab_json.exists():
        return [f"{vocab_json} does not exist"]
    merged, _files = build_vocab.build_merged(vocab_dir)
    try:
        committed = json.loads(vocab_json.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        return [f"{vocab_json}: invalid JSON: {e}"]
    if merged == committed:
        return []
    merged_ids = [e.get("id") for e in merged]
    committed_ids = [e.get("id") for e in committed]
    detail = f"sources have {len(merged)} entries, vocab.json has {len(committed)}"
    missing = sorted(set(merged_ids) - set(committed_ids))
    extra = sorted(set(committed_ids) - set(merged_ids))
    if missing:
        detail += f"; missing from vocab.json (first 10): {missing[:10]}"
    if extra:
        detail += f"; extra in vocab.json not in sources (first 10): {extra[:10]}"
    if not missing and not extra and len(merged) == len(committed):
        detail += "; same ids, different content -- run scripts/build_vocab.py"
    return [f"vocab.json is STALE relative to vocab/*.json ({detail})"]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "paths",
        nargs="*",
        type=Path,
        help="vocab json files to validate (default: <root>/vocab/*.json)",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=ROOT,
        help="repo root used for the zh-transform and staleness checks "
        "(default: this script's own repo; override for isolated fixture "
        "runs)",
    )
    args = parser.parse_args()
    root = args.root
    vocab_dir = root / "vocab"
    paths = args.paths or sorted(
        p for p in vocab_dir.glob("*.json") if p.name != "vocab.json"
    )
    if not paths:
        print(f"no vocab files found under {vocab_dir}", file=sys.stderr)
        sys.exit(1)

    entries = load_entries(paths)
    errors, per_domain = check_basic(entries)

    dup_summary = duplicate_token_audit(entries)

    errors.extend(check_token_collision_annotations(root))
    errors.extend(check_token_notation(entries))
    errors.extend(check_de_eq_en(entries))
    errors.extend(check_zh_traditional(entries, root))
    errors.extend(check_stale(root))
    errors.extend(check_embed_en_truthiness(root))

    print("=== per-domain counts ===")
    for domain in sorted(per_domain):
        print(f"  {domain}: {per_domain[domain]}")
    print(f"  TOTAL: {sum(per_domain.values())}")

    print("\n=== duplicate token audit (per language column; null excluded) ===")
    for lang in LANGS:
        null_count, species, affected, surplus = dup_summary[lang]
        print(
            f"  {lang}: null={null_count}  species={species}  "
            f"affected={affected}  surplus={surplus}"
        )

    if errors:
        print(f"\n=== {len(errors)} error(s) ===", file=sys.stderr)
        for err in errors:
            print(f"  {err}", file=sys.stderr)
        sys.exit(1)

    print("\nOK: no violations")


if __name__ == "__main__":
    main()
